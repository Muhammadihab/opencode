#!/bin/bash
# Update pipeline: fetch -> process -> index -> learn -> briefing
# Offline/sample mode supported
set -e
MODE=${1:-offline}
ROOT=$(dirname $(dirname "$0"))
cd "$ROOT" || exit 1
echo "[fetch] mode=$MODE"
echo "[process] converting raw -> processed"
python -c "
# simple process
import os, glob
raw_dir='writeups/raw'
proc_dir='writeups/processed'
os.makedirs(proc_dir, exist_ok=True)
for f in glob.glob(os.path.join(raw_dir,'*.txt')):
    name=os.path.basename(f).replace('.txt','.md')
    with open(f) as fh:
        data=fh.read()
    # naive parse to structured md
    out_path=os.path.join(proc_dir,name)
    with open(out_path,'w') as of:
        of.write('# Processed\n\n')
        of.write(data)
print('done')
"
echo "[index] rebuilding writeups/index.md"
python -c "
# rebuild index from processed
import os, glob, re
proc_dir='writeups/processed'
rows=[]
for f in sorted(glob.glob(os.path.join(proc_dir,'*.md'))):
    with open(f) as fh:
        txt=fh.read()
    # extract simple fields
    def g(k):
        m=re.search(r'\*\*'+re.escape(k)+r':\*\*\s*(.+)', txt)
        return m.group(1).strip() if m else ''
    rows.append({
        'title': txt.splitlines()[0].lstrip('#').strip(),
        'source':g('Source'),'date':g('Date'),'entry point':g('Entry point'),
        'precondition':g('Precondition'),'trust boundary':g('Trust boundary'),
        'bypass':g('Bypass'),'proof method':g('Proof method'),
        'fp trap':g('FP trap'),'chain opportunity':g('Chain opportunity'),
        'tags':g('Tags')
    })
with open('writeups/index.md','w') as of:
    of.write('# Writeups Index\n\n')
    of.write('| title | source | date | entry point | precondition | trust boundary | bypass | proof method | fp trap | chain opportunity | tags |\n')
    of.write('|---|---|---|---|---|---|---|---|---|---|---|\n')
    for r in rows:
        of.write(f\"| {r['title']} | {r['source']} | {r['date']} | {r['entry point']} | {r['precondition']} | {r['trust boundary']} | {r['bypass']} | {r['proof method']} | {r['fp trap']} | {r['chain opportunity']} | {r['tags']} |\n\")
print('done')
"
echo "[learn] extracting lessons and regenerating briefing"
python -c "
# learn
import os,re
lessons=[]
with open('writeups/index.md') as fh:
    for line in fh:
        if line.startswith('|') and '---' not in line and 'title' not in line:
            parts=[p.strip() for p in line.split('|')]
            if len(parts)>12:
                lessons.append(f'- {parts[1]}: {parts[9]} (tags: {parts[11]})')
os.makedirs('memory',exist_ok=True)
with open('memory/report-lessons.md','w') as of:
    of.write('# Report Lessons\n\n')
    of.write('\n'.join(lessons))
# update patterns/methodology lightly
with open('memory/patterns.md','w') as of:
    of.write('# Patterns\n\n- Auth recovery high-yield\n- GraphQL ownership gaps\n- SSRF chainable\n')
with open('memory/methodology.md','w') as of:
    of.write('# Methodology\n\n1. Scope lock\n2. Skill gate\n3. Exploit-first\n4. FP gate\n5. Evidence\n')
# regenerate briefing
from datetime import date
count = len([l for l in open('writeups/index.md') if l.startswith('|') and '---' not in l and 'title' not in l])
biases='''# KNOWLEDGE STATE (CURRENT LEARNED BIASES)\n\n*(Regenerated by /update.)*\n\n1. **JS intelligence wins hunts.** Deep analysis of JS bundles/source maps often reveals hidden routes, mutations, and auth logic.\n2. **GraphQL authenticates but fails ownership.** AuthN is common; BOLA/IDOR on resolvers/mutations is frequent.\n3. **SSRF strongest when chained.** Internal metadata/service access becomes critical when chained with creds/config exposure.\n4. **Parser differentials create real bypasses.** Content-type/encoding/parser mismatches often bypass filters and validation.\n5. **Auth bugs live in recovery/fallback paths.** Password reset, invite, magic link, MFA fallback, and trust-device flows are high-yield.\n6. **Medium signals become critical chains.** Isolated disclosures (routes/IDs/roles) frequently escalate into ATO/cross-tenant/data exposure.\n'''
# simple replace in briefing
with open('agent-briefing.md') as fh:
    txt=fh.read()
# replace header
txt = re.sub(r'- \*\*Last updated:\*\*.*', f'- **Last updated:** {date.today().isoformat()}', txt)
txt = re.sub(r'- \*\*Knowledge base:\*\*.*', f'- **Knowledge base:** {count} processed write-ups (from `writeups/index.md`)', txt)
# replace biases section
m=re.search(r'# KNOWLEDGE STATE.*?(?=\n# |\Z)', txt, re.S)
if m:
    txt = txt[:m.start()] + biases + txt[m.end():]
with open('agent-briefing.md','w') as of:
    of.write(txt)
print('done')
"
echo "[briefing] regenerated"
echo "PIPELINE_COMPLETE"
